# Separator used to join multiple peptides inside one cell.
JOIN = ";"

# Columns checked for the 'sp|' substring to decide "maps to UniProt".
# Your rule = "Mapped Proteins" only. Add "Protein" here if you also want
# the razor protein assignment (the Protein column) to count as a match.
SP_CHECK_COLUMNS = ["Mapped Proteins", "Protein"]


# ----------------------------------------------------------------------
# LOGIC
# ----------------------------------------------------------------------

def protein_tokens(protein: str, mapped: str) -> set:
    """All protein identifiers referenced by a peptide row."""
    tokens = set()
    if isinstance(protein, str) and protein:
        tokens.add(protein.strip())
    if isinstance(mapped, str) and mapped:
        tokens.update(t.strip() for t in mapped.split(",") if t.strip())
    return tokens


def collect_dataset(samples, target_set, ds):
    """
    Return two dicts keyed by protein:
        all_pep[protein]     -> set of unique peptide sequences
        nomatch_pep[protein] -> subset with no 'sp|' in SP_CHECK_COLUMNS
    """
    all_pep = {p: set() for p in target_set}
    nomatch_pep = {p: set() for p in target_set}

    for sample in samples:
        path = peptide_path(ds, sample)
        df = pd.read_csv(
            path,
            sep="\t",
            usecols=["Peptide", "Protein", "Mapped Proteins"],
            dtype=str,
            keep_default_na=False,  # empty cells become "" not NaN
        )
        cols = {"Protein": df["Protein"], "Mapped Proteins": df["Mapped Proteins"]}
        for i, (peptide, protein, mapped) in enumerate(
            zip(df["Peptide"], df["Protein"], df["Mapped Proteins"])
        ):
            matched = protein_tokens(protein, mapped) & target_set
            if not matched:
                continue
            sp_blob = " ".join(cols[c].iloc[i] for c in SP_CHECK_COLUMNS)
            maps_to_sp = "sp|" in sp_blob
            for prot in matched:
                all_pep[prot].add(peptide)
                if not maps_to_sp:
                    nomatch_pep[prot].add(peptide)

    return all_pep, nomatch_pep


def build_table(proteins, datasets, samples_by_ds):
    target_set = set(proteins)
    per_ds = {ds: collect_dataset(samples_by_ds[ds], target_set, ds) for ds in datasets}

    header = ["protein"]
    for ds in datasets:
        header += [f"{ds}_peptides", f"{ds}_peptides_no_match_sp"]

    rows = [header]
    for prot in proteins:
        row = [prot]
        for ds in datasets:
            all_pep, nomatch_pep = per_ds[ds]
            row.append(JOIN.join(sorted(all_pep[prot])))
            row.append(JOIN.join(sorted(nomatch_pep[prot])))
        rows.append(row)
    return rows


